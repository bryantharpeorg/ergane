@pytest.fixture
def spawn_orphan() -> Iterator[Callable[[], subprocess.Popen[bytes]]]:
    """Start a process in its own session — an agent the worker host forgot (R4).

    Its own session makes its pid its process-group id, which is what a pid file
    from a crashed worker names. Anything still alive at teardown is killed, so a
    failing assertion cannot leave a sleeper behind.
    """
    spawned: list[subprocess.Popen[bytes]] = []

    def spawn() -> subprocess.Popen[bytes]:
        process = subprocess.Popen(
            [sys.executable, "-c", "import time; time.sleep(300)"],
            stdin=subprocess.DEVNULL,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            start_new_session=True,
        )
        spawned.append(process)
        return process

    yield spawn

    for process in spawned:
        if process.poll() is None:
            process.kill()
        with contextlib.suppress(subprocess.TimeoutExpired):
            process.wait(timeout=PATIENCE_S)


