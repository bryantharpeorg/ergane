async def wait_until(
    predicate: Callable[[], bool], *, what: str, timeout_s: float = PATIENCE_S
) -> None:
    """Poll `predicate` until it holds, or fail naming what never happened."""
    deadline = time.monotonic() + timeout_s
    while time.monotonic() < deadline:
        if predicate():
            return
        await asyncio.sleep(0.02)
    raise AssertionError(f"timed out after {timeout_s}s waiting for {what}")


def stub_is_up(worktree: Path) -> bool:
    """Whether a launched stub has finished recording itself.

    Keyed on the stdin record because the stub writes it last, once the prompt is
    drained: by then argv, env, cwd and the process ids are all on disk.
    """
    return bool(list(worktree.glob(".stub-agent/*/stdin.txt")))


def plant_pid_file(factory_root: Path, contents: str) -> Path:
    """Leave `.factory/run/<epic>/<node>.pid` behind, as a dead worker would."""
    path = pid_file(factory_root, EPIC, NODE)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(contents, encoding="utf-8")
    return path


def pid_alive(pid: int) -> bool:
    """Whether signal 0 still finds `pid` (a zombie counts as alive — it exists)."""
    try:
        os.kill(pid, 0)
    except ProcessLookupError:
        return False
    except PermissionError:
        return True
    return True


def archive_dir(factory_root: Path, attempt_number: int = ATTEMPT) -> Path:
    return transcript_dir(factory_root, EPIC, NODE, attempt_number)


def stdout_log(factory_root: Path, attempt_number: int = ATTEMPT) -> str:
    return (archive_dir(factory_root, attempt_number) / STDOUT_LOG_NAME).read_text(
        encoding="utf-8"
    )


def archived_transcript_events(factory_root: Path, attempt_number: int = ATTEMPT) -> list[str]:
    """The `event` field of each record in the archived session transcript.

    `["start"]` alone is a run that was killed between the two writes — the
    partial evidence FR-007 exists to keep.
    """
    path = archive_dir(factory_root, attempt_number) / f"{SESSION_ID}.jsonl"
    lines = path.read_text(encoding="utf-8").splitlines()
    return [json.loads(line)["event"] for line in lines if line.strip()]


def git_commit_in_child_environment(
    cwd: Path,
    home: Path,
    env: dict[str, str],
) -> subprocess.CompletedProcess[str]:
    """Make a git commit inside `cwd` using only the constructed child environment.

    The environment is the adapter's `attempt_env` output plus `ATTEMPT_ARCHIVE`
    if present. This is *not* a test helper that smuggles `GIT_AUTHOR_*` in:
    the assertion is that the home's `.gitconfig` provides identity.
    """
    return subprocess.run(
        ["git", "commit", "--quiet", "--allow-empty", "-m", "agent commit"],
        cwd=str(cwd),
        env=env,
        capture_output=True,
        text=True,
    )


def git_show_field(cwd: Path, field: str) -> str:
    """One commit field, e.g. `%an` or `%ae`, from HEAD."""
    return subprocess.run(
        ["git", "-C", str(cwd), "log", "-1", f"--format={field}"],
        capture_output=True,
        text=True,
        check=True,
    ).stdout.strip()


