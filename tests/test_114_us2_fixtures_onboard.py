@pytest.mark.parametrize(
    "module", COVERED_LIVE_MODULES, ids=lambda module: module.filename
)
def test_the_filter_is_applied_where_the_module_dispatches_halting(
    module: CoveredLiveModule, tmp_path: Path
) -> None:
    """FR-005: the filter is applied when, and only when, the epic will not land.

    Two ways this check could quietly stop proving anything, both closed here.
    It could forgive landing findings for a module that dispatches normally —
    so the flag is read from the module's own dispatch. And it could be
    vacuously green because onboarding refused nothing at all — so the
    unfiltered profile is asserted to still carry failures, every one of them
    landing-only, for a repository whose dispatch halts.
    """
    root = tmp_path / module.filename
    repo = module.build_scratch_repo(root / "target-repo")
    halting = module.dispatched_epic_input(root).halt_after_pass

    unfiltered = blocking_findings(repo, halting=False)
    if not halting:
        assert not unfiltered, (
            f"{module.filename} dispatches without halting, so nothing about its "
            "repository may be forgiven:\n" + render_findings(unfiltered)
        )
        return

    assert unfiltered, (
        f"onboarding now refuses nothing about {module.filename}'s scratch "
        "repository, so the landing-only filter proves nothing here any more"
    )
    assert all(_is_landing_only_check(finding.check) for finding in unfiltered), (
        f"onboarding refuses {module.filename}'s repository for something the "
        "halting dispatch does not forgive:\n" + render_findings(unfiltered)
    )


def test_the_landing_only_predicate_is_imported_not_restated() -> None:
    """FR-005, plan T3: one list, in the workflow, and this module reads it.

    Identity first — the name this module filters with is the workflow's own
    function object, not a lookalike — and then the thing identity cannot see:
    that no check name or prefix from `_LANDING_ONLY_CHECKS` has been copied
    into this module's code. Restating them is faster and is exactly what
    leaves two lists that drift while both stay green; this repository has the
    receipts for that failure mode three times over in `tests/page_holds_true.py`.
    """
    assert _is_landing_only_check is workflow_module._is_landing_only_check

    code = code_without_prose(Path(__file__).read_text(encoding="utf-8"))
    restated = sorted(
        name
        for name in (
            *workflow_module._LANDING_ONLY_CHECKS,
            *workflow_module._LANDING_ONLY_CHECK_PREFIXES,
        )
        if name in code
    )
    assert not restated, (
        f"this module writes the landing-only check names {restated} into its own "
        "code; it must ask `_is_landing_only_check`, so that the day a fifth "
        "landing check is added the filter follows it"
    )


def test_a_broken_manifest_is_reported_by_name(tmp_path: Path) -> None:
    """US2-S2, FR-006: the failure names the check and the detail, not a boolean.

    Driven against a repository whose manifest declares a backend that does not
    exist, so what the message must carry is unambiguous: the failing check's
    name, the value the manifest declares, and the backend the loader supports.
    """
    repo = smoke.build_scratch_repo(tmp_path / "target-repo")
    declare_runtime(repo, "not-a-backend")

