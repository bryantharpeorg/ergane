class _CapturingClient:
    """A Temporal client that records the dispatch instead of sending it.

    How a live module's dispatch mode is *read* rather than assumed: its own
    `start` is called with this in place of a client, and the `EpicInput` it
    constructs is the answer to whether the landing-only filter applies.
    """

    def __init__(self) -> None:
        self.epic_input: Any = None

    async def start_workflow(
        self, workflow: Any, epic_input: Any, /, **kwargs: Any
    ) -> Any:
        self.epic_input = epic_input
        return object()  # the handle; nothing here reads it


def smoke_dispatch(root: Path) -> Any:
    """The `EpicInput` `tests/test_live_epic.py` would dispatch, captured not sent.

    `start` only passes its config and workspace through to the client, so both
    address nothing that has to exist: no proxy is reached, no server is
    contacted and no path is written.
    """
    client = _CapturingClient()
    epic_id = "live-epic-offline"
    config = smoke.LiveConfig(
        proxy_url="http://127.0.0.1:1",
        master_key="not-a-key",
        model_alias="not-an-alias",
        address="127.0.0.1:1",
        namespace="ergane",
        timeout_s=1,
    )
    workspace = smoke.Workspace(
        epic_id=epic_id,
        target_repo=root / "target-repo",
        specs_root=root / "specs",
        spec_dir=root / "specs" / epic_id,
        factory_root=root / ".factory",
        ledger_path=root / ".factory" / "ledger.db",
        verification_db=root / ".factory" / "verification.db",
        task_queue=f"workgraph-{epic_id}",
    )
    asyncio.run(smoke.start(client, config, workspace, object()))
    return client.epic_input


