def test_the_check_fails_when_the_smoke_s_runtime_is_reverted(tmp_path: Path) -> None:
    """US2-S4, FR-006: put the refused runtime back, and this goes red by name.

    A copy of the corrected repository, reverted in the copy alone, so the
    fixture US1 fixed is left exactly as it is and this still observes the
    guard failing on the defect that produced the story. Both halves of the
    message matter: the runtime the manifest declares is what to change, and
    the supported backend is what to change it to.
    """
    corrected = smoke.build_scratch_repo(tmp_path / "target-repo")
    check_repository_onboards(SMOKE_FILENAME, corrected, halting=True)

    reverted = tmp_path / "reverted-repo"
    shutil.copytree(corrected, reverted)
    declare_runtime(reverted, REFUSED_RUNTIME)

    with pytest.raises(AssertionError) as raised:
        check_repository_onboards(SMOKE_FILENAME, reverted, halting=True)

    message = str(raised.value)
    assert REFUSED_RUNTIME in message, message
    assert SUPPORTED_BACKENDS[0] in message, message


# --- US2-S3: the covered set is not enumerated by hand alone ------------------


def test_the_guard_demands_coverage_of_every_hand_authored_manifest() -> None:
    """US2-S3, FR-007: every live module that writes its own manifest is covered.

    The failure this exists to prevent is a fourth live module arriving with a
    hand-written manifest while the suite stays green, so the set it judges is
    discovered rather than listed, and the covered names are checked to still
    name modules that exist.
    """
    discovered = discover_live_modules()
    assert discovered, (
        f"no {LIVE_MODULE_GLOB} module was found under {TESTS_DIR}; a guard whose "
        "discovery finds nothing reports zero uncovered modules forever"
    )
    names = {path.name for path in discovered}
    assert COVERED_FILENAMES <= names, (
        f"this module claims to cover {sorted(COVERED_FILENAMES - names)}, which "
        f"no longer exists under {TESTS_DIR}"
    )

    unseen = sorted(
        filename
        for filename in COVERED_FILENAMES
        if not hand_authors_manifest(TESTS_DIR / filename)
    )
    assert not unseen, (
        f"the guard reads {unseen} as writing no manifest of its own, while this "
        "module covers it for doing exactly that — either the module stopped and "
        "its coverage should go, or the guard has stopped seeing manifests and is "
        "now reporting zero uncovered modules about nothing"
    )

    uncovered = uncovered_live_modules(discovered)
    assert not uncovered, (
        "these live modules hand-author a repository manifest and nothing cheap "
        "ever reads it:\n"
        + "\n".join(f"  {path.name}" for path in uncovered)
        + f"\nAdd each to {Path(__file__).name}'s COVERED_LIVE_MODULES."
    )


def test_the_guard_fails_on_a_module_that_writes_its_own_manifest(
    tmp_path: Path,
) -> None:
    """US2-S3, plan T5: proven by watching the guard turn red, not by trusting it.

    A throwaway module that hand-authors a manifest is added to the discovered
    set, and the guard must name it. Without this, "zero uncovered modules" is a
    claim about the guard's discovery and not about the tier — the vacuous sweep
    this repository has shipped before.
    """
    throwaway = tmp_path / "test_live_throwaway.py"
    throwaway.write_text(throwaway_module_source(), encoding="utf-8")

    assert hand_authors_manifest(throwaway), (
        "the guard does not see a manifest written as a literal, so it would not "
        "see one in a real live module either"
    )
    uncovered = uncovered_live_modules([*discover_live_modules(), throwaway])
    assert throwaway in uncovered, (
        "the guard passed a live module that hand-authors a manifest and is not "
        f"covered; it reported {[path.name for path in uncovered]}"
    )

    silent = tmp_path / "test_live_silent.py"
    silent.write_text(
        '"""A live module that builds no repository at all."""\n', encoding="utf-8"
    )
    assert silent not in uncovered_live_modules([silent]), (
        "the guard demands coverage of a live module that writes no manifest, so "
        "it is failing on the glob rather than on the hazard"
    )


def test_the_guard_does_not_demand_the_generated_manifest() -> None:
    """US2-S3, FR-007: a manifest `ergane init` writes is outside the rule.

    `tests/test_live_onramp.py` ends up with a manifest, but it is generated by
    `ergane init --wire` and then read by the real loader
    (`tests/test_live_onramp.py:687-694`): writer and reader are the same code,
    so it cannot drift the way a literal can, and `--wire` needs a real forge,
    so its repository cannot be built offline at all. A guard that demanded it
    would demand something impossible and be relaxed within the hour.
    """
    onramp = TESTS_DIR / "test_live_onramp.py"
    assert onramp.is_file(), f"{onramp} has been renamed; this test names it"

    assert not hand_authors_manifest(onramp), (
        f"{onramp.name} is read as hand-authoring a manifest, so the guard now "
        "demands offline coverage of a repository only `ergane init --wire` can "
        "build"
    )
    assert onramp not in uncovered_live_modules(discover_live_modules())


# --- helpers used by the tests above ------------------------------------------


def declare_runtime(repo: Path, runtime: str) -> None:
    """Rewrite the manifest's `runtime:` line in place, and prove it changed."""
    manifest, _name = resolve_manifest_path(repo)
    source = manifest.read_text(encoding="utf-8")
    rewritten = re.sub(r"(?m)^runtime:.*$", f"runtime: {runtime}", source)
    assert rewritten != source, (
        f"{manifest} declares no `runtime:` line to rewrite:\n{source}"
    )
    manifest.write_text(rewritten, encoding="utf-8")


def throwaway_module_source() -> str:
    """A live-looking module that hand-authors a manifest, for the guard's test.

    The backend it declares is interpolated for the same reason `manifest_source`
    interpolates it: no file in this repository should carry a supported backend
    name as a literal, not even a fixture that exists to be thrown away.
    """
    manifest = "\n".join(
        (
            "version: 1",
            f"runtime: {SUPPORTED_BACKENDS[0]}",
            "",
            "gates:",
            '  test: "pytest -q"',
            "",
            "standards: STANDARDS.md",
        )
    )
    return (
        '"""A live module that writes its own manifest — the shape FR-007 names."""\n'
        "\n\n"
        "def build_scratch_repo(path):\n"
        f"    (path / 'factory.yaml').write_text({manifest!r}, encoding='utf-8')\n"
    )
